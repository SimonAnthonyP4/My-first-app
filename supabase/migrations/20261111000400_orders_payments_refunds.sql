-- Bro Batch M1 — orders, payments and refunds.
--
-- All money is integer cents. No sales tax is charged, so
--   total = subtotal - discount - reward.
-- These tables are written only by server-side code (service role). No client
-- role is granted INSERT/UPDATE/DELETE on any of them.
-- Card data never lives here: only provider ids plus brand/last4 for display.

create type public.order_status as enum (
  'pending', 'paid', 'partially_refunded', 'refunded', 'cancelled', 'failed'
);

create table public.orders (
  id               uuid primary key default gen_random_uuid(),
  order_number     bigint generated always as identity unique,
  customer_id      uuid references public.customers (id) on delete restrict,
  employee_id      uuid not null references public.employees (id) on delete restrict,
  status           public.order_status not null default 'pending',
  subtotal_cents   bigint not null check (subtotal_cents >= 0),
  discount_cents   bigint not null default 0 check (discount_cents >= 0),
  reward_cents     bigint not null default 0 check (reward_cents >= 0),
  total_cents      bigint not null check (total_cents >= 0),
  points_reserved  bigint not null default 0 check (points_reserved >= 0),
  points_awarded   bigint not null default 0 check (points_awarded >= 0),
  -- One key per checkout attempt, generated by the POS. A retried request
  -- with the same key must return the same order, never a second one.
  idempotency_key  text not null unique check (char_length(idempotency_key) between 8 and 200),
  created_at       timestamptz not null default now(),
  paid_at          timestamptz,
  constraint orders_total_matches
    check (total_cents = subtotal_cents - discount_cents - reward_cents),
  constraint orders_paid_at_matches_status
    check ((status in ('paid', 'partially_refunded', 'refunded')) = (paid_at is not null)),
  constraint orders_points_need_customer
    check (customer_id is not null or (points_reserved = 0 and points_awarded = 0))
);

create index orders_customer_idx on public.orders (customer_id, created_at desc)
  where customer_id is not null;
create index orders_employee_idx on public.orders (employee_id, created_at desc);
create index orders_created_idx on public.orders (created_at desc);
create index orders_status_idx on public.orders (status, created_at desc);

create table public.order_items (
  id                 uuid primary key default gen_random_uuid(),
  order_id           uuid not null references public.orders (id) on delete restrict,
  product_id         uuid not null references public.products (id) on delete restrict,
  -- Snapshot at sale time, so later catalog edits do not rewrite history.
  product_name       text not null,
  flavor             text not null,
  bar_count          integer not null check (bar_count >= 0),
  unit_price_cents   bigint not null check (unit_price_cents >= 0),
  quantity           integer not null check (quantity > 0),
  line_total_cents   bigint not null,
  refunded_quantity  integer not null default 0,
  constraint order_items_line_total_matches
    check (line_total_cents = unit_price_cents * quantity),
  constraint order_items_refunded_quantity_range
    check (refunded_quantity between 0 and quantity)
);

create index order_items_order_idx on public.order_items (order_id);
create index order_items_product_idx on public.order_items (product_id);

create table public.payments (
  id                       uuid primary key default gen_random_uuid(),
  order_id                 uuid not null references public.orders (id) on delete restrict,
  provider                 text not null default 'stripe' check (provider = 'stripe'),
  provider_payment_intent  text not null unique check (provider_payment_intent ~ '^pi_[A-Za-z0-9_]+$'),
  provider_charge_id       text unique check (provider_charge_id ~ '^(ch|py)_[A-Za-z0-9_]+$'),
  amount_cents             bigint not null check (amount_cents > 0),
  currency                 text not null default 'usd' check (currency = 'usd'),
  status                   text not null
                             check (status in (
                               'requires_payment_method', 'processing', 'succeeded', 'canceled', 'failed'
                             )),
  card_brand               text check (char_length(card_brand) <= 30),   -- display only
  card_last4               text check (card_last4 ~ '^[0-9]{4}$'),        -- display only
  reader_type              text check (reader_type in ('tap_to_pay', 'reader', 'simulated')),
  created_at               timestamptz not null default now(),
  updated_at               timestamptz not null default now(),
  succeeded_at             timestamptz,
  constraint payments_succeeded_at_matches_status
    check ((status = 'succeeded') = (succeeded_at is not null))
);

create index payments_order_idx on public.payments (order_id);
-- An order can be charged successfully at most once.
create unique index payments_one_success_per_order
  on public.payments (order_id) where status = 'succeeded';

create table public.refunds (
  id                  uuid primary key default gen_random_uuid(),
  order_id            uuid not null references public.orders (id) on delete restrict,
  payment_id          uuid not null references public.payments (id) on delete restrict,
  amount_cents        bigint not null check (amount_cents > 0),
  reason              text not null
                        check (reason in ('customer_request', 'damaged', 'wrong_item', 'duplicate', 'other')),
  note                text check (char_length(note) <= 500),
  status              text not null default 'pending'
                        check (status in ('pending', 'succeeded', 'failed', 'canceled')),
  provider_refund_id  text unique check (provider_refund_id ~ '^re_[A-Za-z0-9_]+$'),
  idempotency_key     text not null unique check (char_length(idempotency_key) between 8 and 200),
  requested_by        uuid not null references public.employees (id) on delete restrict,
  approved_by         uuid references public.employees (id) on delete restrict,
  points_reversed     bigint not null default 0 check (points_reversed >= 0),
  created_at          timestamptz not null default now(),
  completed_at        timestamptz,
  constraint refunds_completed_at_matches_status
    check ((status in ('succeeded', 'failed', 'canceled')) = (completed_at is not null))
);

create index refunds_order_idx on public.refunds (order_id);
create index refunds_payment_idx on public.refunds (payment_id);
create index refunds_created_idx on public.refunds (created_at desc);

create table public.refund_items (
  refund_id      uuid not null references public.refunds (id) on delete restrict,
  order_item_id  uuid not null references public.order_items (id) on delete restrict,
  quantity       integer not null check (quantity > 0),
  primary key (refund_id, order_item_id)
);

create index refund_items_order_item_idx on public.refund_items (order_item_id);

alter table public.inventory_movements
  add constraint inventory_movements_order_id_fkey
  foreign key (order_id) references public.orders (id) on delete restrict;
