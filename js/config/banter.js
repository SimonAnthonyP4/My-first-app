// [line for p1, line for p2] or null.
RF.banterFor = (a, b) => {
  if (a === b) return ['THERE CAN ONLY BE ONE.', 'AGREED.'];
  if (RF.BANTER[a + '|' + b]) return RF.BANTER[a + '|' + b];
  const r = RF.BANTER[b + '|' + a];
  return r ? [r[1], r[0]] : null;
};
